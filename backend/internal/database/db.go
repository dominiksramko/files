func Open(dbPath string) (*sql.DB, error) {
	if err := os.MkdirAll(filepath.Dir(dbPath), 0o755); err != nil {
		return nil, fmt.Errorf("create db dir: %w", err)
	}

	db, err := sql.Open("sqlite", dbPath)
	if err != nil {
		return nil, fmt.Errorf("open sqlite: %w", err)
	}

	db.SetMaxOpenConns(1) // SQLite is single-writer

	if err := runMigrations(db); err != nil {
		db.Close()
		return nil, fmt.Errorf("migrate: %w", err)
	}

	return db, nil
}

func runMigrations(db *sql.DB) error {
	// Ensure the tracking table exists before anything else.
	if _, err := db.Exec(`
		CREATE TABLE IF NOT EXISTS migrations (
			version    TEXT PRIMARY KEY,
			name       TEXT NOT NULL,
			applied_at TEXT NOT NULL DEFAULT (datetime('now'))
		)
	`); err != nil {
		return fmt.Errorf("create migrations table: %w", err)
	}

	// Load already-applied versions.
	rows, err := db.Query(`SELECT version FROM migrations`)
	if err != nil {
		return fmt.Errorf("query migrations: %w", err)
	}
	applied := make(map[string]bool)
	for rows.Next() {
		var v string
		if err := rows.Scan(&v); err != nil {
			rows.Close()
			return err
		}
		applied[v] = true
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return err
	}

	// Apply any pending migrations in version order.
	for _, m := range migrations.All() {
		if applied[m.Version] {
			continue
		}
		if err := applyMigration(db, m); err != nil {
			return fmt.Errorf("migration %s (%s): %w", m.Version, m.Name, err)
		}
		log.Printf("db: applied migration %s_%s", m.Version, m.Name)
	}

	return seedAdmin(db)
}

func applyMigration(db *sql.DB, m migrations.Migration) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()

	if err := m.Up(tx); err != nil {
		return err
	}

	if _, err := tx.Exec(
		`INSERT INTO migrations (version, name) VALUES (?, ?)`,
		m.Version, m.Name,
	); err != nil {
		return err
	}

	return tx.Commit()
}

func seedAdmin(db *sql.DB) error {
	var count int
	if err := db.QueryRow(`SELECT COUNT(*) FROM users`).Scan(&count); err != nil {
		return err
	}
	if count > 0 {
		return nil
	}

	username := os.Getenv("ADMIN_USERNAME")
	if username == "" {
		username = "admin"
	}

	// The admin's folder: ADMIN_PATH, or a folder named after them in
	// USERS_ROOT (created now), as for users added later.
	rootDir := os.Getenv("ADMIN_PATH")
	if rootDir == "" {
		usersRoot := os.Getenv("USERS_ROOT")
		if usersRoot == "" {
			usersRoot = config.DefaultUsersRoot
		}
		rootDir = filepath.Join(usersRoot, username)
		if err := os.MkdirAll(rootDir, 0o755); err != nil {
			log.Printf("db: could not create the admin's folder %s: %v", rootDir, err)
		}
	}

	password := os.Getenv("ADMIN_PASSWORD")
	autoGenerated := password == ""
	if autoGenerated {
		b := make([]byte, 16)
		if _, err := rand.Read(b); err != nil {
			return fmt.Errorf("generate admin password: %w", err)
		}
		password = hex.EncodeToString(b)
	}

	hash, err := bcrypt.GenerateFromPassword([]byte(password), bcrypt.DefaultCost)
	if err != nil {
		return err
	}

	if _, err = db.Exec(
		`INSERT INTO users (username, password, root_dir, is_admin) VALUES (?, ?, ?, 1)`,
		username, string(hash), rootDir,
	); err != nil {
		return err
	}

	if autoGenerated {
		log.Printf("================================================================")
		log.Printf("  ADMIN ACCOUNT CREATED")
		log.Printf("  Username : %s", username)
		log.Printf("  Password : %s", password)
		log.Printf("  Change this password after your first login!")
		log.Printf("================================================================")
	} else {
		log.Printf("db: seeded admin user %q", username)
	}

	return nil
}
